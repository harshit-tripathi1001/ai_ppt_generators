"""Content schema definition for presentations and slides.

Defines the structured representations for presentation metadata,
individual slide elements, layouts, and supporting data (KPIs, tables, charts).
"""

from typing import List, Optional, Dict, Any, Union
from pydantic import BaseModel, Field


class KpiMetric(BaseModel):
    """Key Performance Indicator or metric item."""
    label: str = Field(description="Metric label or description, e.g., 'Accuracy Rate'")
    value: str = Field(description="Metric value or statistic, e.g., '99.4%' or '10x'")
    detail: Optional[str] = Field(default="", description="Optional short context or subtext")


class ColumnData(BaseModel):
    """Two-column layout representation."""
    col1_title: str = Field(default="Key Aspect A", description="Title for left column")
    col1_bullets: List[str] = Field(default_factory=list, description="Bullets for left column")
    col2_title: str = Field(default="Key Aspect B", description="Title for right column")
    col2_bullets: List[str] = Field(default_factory=list, description="Bullets for right column")


class TableData(BaseModel):
    """Tabular data representation for table slides."""
    headers: List[str] = Field(default_factory=list, description="Column header labels")
    rows: List[List[str]] = Field(default_factory=list, description="Matrix of row data strings")


class ChartSeries(BaseModel):
    """Single series in a chart."""
    name: str = Field(description="Series name, e.g., '2024'")
    values: List[Union[int, float]] = Field(description="Numerical values corresponding to categories")


class ChartData(BaseModel):
    """Data representation for genuine PowerPoint editable charts."""
    chart_type: str = Field(default="column", description="Type: column, bar, line, pie")
    title: Optional[str] = Field(default="", description="Chart title")
    categories: List[str] = Field(default_factory=list, description="Categories / X-axis labels")
    series: List[ChartSeries] = Field(default_factory=list, description="One or more data series")


class ProcessStep(BaseModel):
    """A step in a process or timeline layout."""
    step_number: int = Field(default=1, description="Step order number (1, 2, 3...)")
    title: str = Field(description="Step title, e.g., 'Data Collection'")
    description: str = Field(description="Concise description of the step")


class SlideContent(BaseModel):
    """Schema for an individual presentation slide."""
    slide_id: Optional[int] = Field(default=None, description="Sequential slide index starting from 1")
    title: str = Field(description="Main title of the slide")
    layout: str = Field(
        default="bullet_list",
        description="Layout style: title, agenda, bullet_list, two_column, stats_kpi, "
                    "image_text, process_flow, table, chart, section_header, conclusion, references, ending"
    )
    key_message: Optional[str] = Field(default="", description="Core takeaway or summary for this slide")
    bullets: List[str] = Field(default_factory=list, description="Ordered bullet points (typically 3-5)")
    columns: Optional[ColumnData] = Field(default=None, description="Data for two_column layout")
    stats: Optional[List[KpiMetric]] = Field(default=None, description="Data for stats_kpi layout")
    table_data: Optional[TableData] = Field(default=None, description="Data for table layout")
    chart_data: Optional[ChartData] = Field(default=None, description="Data for chart layout")
    process_steps: Optional[List[ProcessStep]] = Field(default=None, description="Steps for process_flow layout")
    visual_description: Optional[str] = Field(
        default="",
        description="Description of visual asset, diagram, or image subject for this slide"
    )
    image_query: Optional[str] = Field(default="", description="Short search keyword for royalty-free image")
    speaker_notes: Optional[str] = Field(default="", description="Comprehensive speaker script for the presenter")


class PresentationData(BaseModel):
    """Top-level presentation schema generated by AI or imported by user."""
    title: str = Field(description="Primary title of the presentation")
    subtitle: str = Field(default="A Professional Presentation", description="Subtitle or tagline")
    overview: Optional[str] = Field(default="", description="Executive summary / overview")
    target_audience: Optional[str] = Field(default="General Audience", description="Target audience definition")
    key_objectives: Optional[List[str]] = Field(default_factory=list, description="Main goals or learning outcomes")
    slides: List[SlideContent] = Field(default_factory=list, description="Ordered list of slide objects")
    metadata: Optional[Dict[str, Any]] = Field(default_factory=dict, description="Generation metadata and parameters")


# Valid layouts catalogue
VALID_LAYOUTS = [
    "title",
    "agenda",
    "bullet_list",
    "two_column",
    "stats_kpi",
    "image_text",
    "process_flow",
    "table",
    "chart",
    "section_header",
    "conclusion",
    "references",
    "ending"
]

